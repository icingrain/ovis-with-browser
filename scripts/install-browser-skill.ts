/**
 * Installs the "ovis-browser" skill into the agents that read SKILL.md folders, so an agent knows to
 * start its Chrome through scripts/ovis-browser.ts (which registers it for the pane for Ovis's Browser tab).
 *
 *   install-browser-skill.ts                    show what would be written, write nothing
 *   install-browser-skill.ts --yes              write it
 *   install-browser-skill.ts --remove --yes     remove what this installer wrote
 *   --agent claude|codex|opencode               limit to one (repeatable); by default every agent whose folder exists
 *
 * Only a SKILL.md carrying this installer's banner is replaced or removed; a file anyone else wrote is left alone.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, rmdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";

export const SKILL_NAME = "ovis-browser";
export const SKILL_BANNER = "<!-- Generated by the Ovis Browser tab skill installer; do not edit. -->";
export const AGENTS = ["claude", "codex", "opencode"] as const;
export type SkillAgent = typeof AGENTS[number];

export interface InstallBrowserSkillOptions {
  agents?: SkillAgent[];
  remove?: boolean;
  write?: boolean;
  home?: string;
  env?: Record<string, string | undefined>;
  platform?: NodeJS.Platform;
  /** the repository (or plugin) root whose scripts/ovis-browser.ts the skill runs */
  root?: string;
}

export interface SkillTarget { agent: SkillAgent; agentDir: string; file: string }
export interface SkillResult { agent: SkillAgent; file: string; action: "installed" | "updated" | "removed" | "would-install" | "would-remove" | "kept" | "absent"; note?: string }

/** Where each agent reads skills from, honouring the variables the agents themselves read. */
export function skillTargets(home: string, env: Record<string, string | undefined>): SkillTarget[] {
  const claude = env["CLAUDE_CONFIG_DIR"] || join(home, ".claude");
  const codex = env["CODEX_HOME"] || join(home, ".codex");
  const opencode = join(env["XDG_CONFIG_HOME"] || join(home, ".config"), "opencode");
  return [
    { agent: "claude", agentDir: claude, file: join(claude, "skills", SKILL_NAME, "SKILL.md") },
    { agent: "codex", agentDir: codex, file: join(codex, "skills", SKILL_NAME, "SKILL.md") },
    { agent: "opencode", agentDir: opencode, file: join(opencode, "skills", SKILL_NAME, "SKILL.md") },
  ];
}

/** The command the skill tells an agent to run: the helper script through the repo's Bun launcher. */
export function helperCommand(root: string, platform: NodeJS.Platform): string {
  const script = join(root, "scripts", "ovis-browser.ts");
  return platform === "win32" ? `bun "${script}"` : `sh "${join(root, "scripts", "with-bun.sh")}" "${script}"`;
}

/** The skill file: the template with the helper command filled in and the banner under the front matter. */
export function renderSkill(template: string, helper: string): string {
  const filled = template.replaceAll("{{HELPER}}", helper);
  const end = filled.indexOf("\n---\n", 4);
  if (!filled.startsWith("---\n") || end === -1) throw new Error("The skill template has no front matter");
  const at = end + "\n---\n".length;
  return `${filled.slice(0, at)}${SKILL_BANNER}\n${filled.slice(at)}`;
}

export function installBrowserSkill(options: InstallBrowserSkillOptions = {}): SkillResult[] {
  const home = options.home ?? homedir();
  const env = options.env ?? process.env;
  const root = options.root ?? resolve(dirname(import.meta.filename), "..");
  const template = readFileSync(join(root, "integrations", "ovis-browser-skill.md"), "utf8");
  const content = renderSkill(template, helperCommand(root, options.platform ?? process.platform));
  const chosen = options.agents ?? [];
  return skillTargets(home, env).flatMap((target): SkillResult[] => {
    if (chosen.length > 0 ? !chosen.includes(target.agent) : !existsSync(target.agentDir)) return [];
    const { agent, file } = target;
    const existing = existsSync(file) ? readFileSync(file, "utf8") : null;
    const ours = existing !== null && existing.includes(SKILL_BANNER);
    if (options.remove) {
      if (existing === null) return [{ agent, file, action: "absent" }];
      if (!ours) return [{ agent, file, action: "kept", note: "not written by this installer" }];
      if (!options.write) return [{ agent, file, action: "would-remove" }];
      rmSync(file);
      try { rmdirSync(dirname(file)); } catch { /* the folder holds something else */ }
      return [{ agent, file, action: "removed" }];
    }
    if (existing !== null && !ours) return [{ agent, file, action: "kept", note: "a skill of that name already exists and is not ours" }];
    if (!options.write) return [{ agent, file, action: "would-install" }];
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    return [{ agent, file, action: existing === null ? "installed" : "updated" }];
  });
}

export function parseSkillArguments(args: string[]): InstallBrowserSkillOptions {
  const options: InstallBrowserSkillOptions = { agents: [] };
  for (let index = 0; index < args.length; index++) {
    const arg = args[index]!;
    if (arg === "--yes") options.write = true;
    else if (arg === "--remove") options.remove = true;
    else if (arg === "--agent") {
      const value = args[++index];
      if (!AGENTS.includes(value as SkillAgent)) throw new Error(`--agent takes one of ${AGENTS.join(", ")}`);
      options.agents!.push(value as SkillAgent);
    } else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

if (import.meta.main) {
  try {
    const options = parseSkillArguments(Bun.argv.slice(2));
    const results = installBrowserSkill(options);
    if (results.length === 0) console.log("No agent folder found (looked for Claude Code, Codex and OpenCode); pass --agent to install anyway.");
    for (const result of results) console.log(`${result.action.padEnd(13)} ${result.agent.padEnd(9)} ${result.file}${result.note ? `  (${result.note})` : ""}`);
    if (results.some((result) => result.action.startsWith("would-"))) console.log("\nNothing was written. Add --yes to apply.");
    else if (results.some((result) => result.action === "installed" || result.action === "updated")) console.log("\nRestart running agent sessions so they load the skill.");
  } catch (error) {
    console.error(`browser skill installer failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
